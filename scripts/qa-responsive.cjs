const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  fs.mkdirSync('qa', { recursive: true });
  const results = [];
  for (const width of [1440, 960, 768, 390, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:5180/');
    const button = name => page.getByRole('button', { name, exact: true });
    const choose = async (label, value) => { await button(label).click(); await button(value).click(); };
    const check = async step => {
      assert.equal(await page.getByText(`PASO ${step} DE 4`, { exact: true }).count(), 1);
      const overflow = await page.evaluate(() => Array.from(document.querySelectorAll('body *')).filter(el => {
        const r = el.getBoundingClientRect(); return r.width > 0 && (r.right > innerWidth + 1 || r.left < -1);
      }).length);
      assert.equal(overflow, 0, `overflow at ${width} step ${step}`);
      assert.equal(await page.getByRole('tab').count(), 0);
    };
    await check(1);
    await button('Siguiente →').click();
    await page.getByRole('alert').waitFor();
    await choose('Tipo de proyecto', 'Residencial');
    await button('Siguiente →').click();
    await page.getByText('Selecciona un área e indica el municipio.', { exact: true }).waitFor();
    await choose('Área a transformar', 'Sala y comedor');
    await page.getByRole('textbox', { name: 'Municipio', exact: true }).fill('Ponce');
    await page.screenshot({ path: `qa/start-${width}.png` });
    await button('Siguiente →').click();
    await check(2);
    await button('Siguiente →').click();
    await page.getByRole('alert').waitFor();
    await choose('Lo más importante para ti', 'Control solar');
    await button('Tipo de cortina').click();
    await page.getByRole('button', { name: /Roll Up Shades/ }).click();
    await button('← Atrás').click();
    assert.equal(await page.getByRole('textbox', { name: 'Municipio', exact: true }).inputValue(), 'Ponce');
    await button('Siguiente →').click();
    await button('Siguiente →').click();
    await check(3);
    await button('+ Añadir otra ventana').click();
    await page.getByText('Ventana 2', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Quitar', exact: true }).last().click();
    await button('Omitir medidas y seguir →').click();
    await check(4);
    await button('Someter · prueba →').click();
    await page.getByRole('alert').waitFor();
    await choose('Ventana tentativa', 'Miércoles · 10:30 AM');
    await page.getByRole('textbox', { name: 'Nombre ficticio', exact: true }).fill('Cliente Demo');
    await page.getByRole('textbox', { name: 'Teléfono ficticio', exact: true }).fill('----------');
    await button('Someter · prueba →').click();
    await page.getByRole('alert').waitFor();
    await page.getByRole('textbox', { name: 'Teléfono ficticio', exact: true }).fill('787-000-0000');
    await page.screenshot({ path: `qa/review-${width}.png` });
    await button('Someter · prueba →').click();
    await page.getByText('SIMULACIÓN COMPLETADA', { exact: true }).waitFor();
    assert.equal(await page.getByText('Solicitud recibida', { exact: true }).count(), 0);
    await button('Volver a revisar').click();
    await check(4);
    await button('Someter · prueba →').click();
    await button('Crear otro proyecto').click();
    await check(1);
    assert.equal(await page.getByRole('textbox', { name: 'Municipio', exact: true }).inputValue(), '');
    assert.deepEqual(errors, []);
    results.push({ width, status: 'PASS', flow: 'validation/back/optional-measures/review/demo-submit/reset', pageErrors: errors });
    await page.close();
  }
  console.log(JSON.stringify(results, null, 2));
  fs.writeFileSync('qa/results.json', JSON.stringify(results, null, 2));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
